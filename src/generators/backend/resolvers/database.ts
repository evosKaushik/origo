function sourceFile(
  language: BackendLanguage,
  folder: string,
  name: string,
  typescript: string,
  javascript: string
): DatabaseGeneratedFile {
  return {
    path: `src/${folder}/${name}.${
      language === "typescript" ? "ts" : "js"
    }`,
    content: language === "typescript" ? typescript : javascript,
  };
}

function databaseConfig(
  language: BackendLanguage,
  typescript: string,
  javascript: string
): DatabaseGeneratedFile {
  return sourceFile(language, "config", "database", typescript, javascript);
}

function todoModel(
  language: BackendLanguage,
  typescript: string,
  javascript: string
): DatabaseGeneratedFile {
  return sourceFile(language, "models", "todo", typescript, javascript);
}

function todoService(
  language: BackendLanguage,
  typescript: string,
  javascript: string
): DatabaseGeneratedFile {
  return sourceFile(language, "services", "todos", typescript, javascript);
}

