export function resolveDatabaseSetup(
  language: BackendLanguage,
  framework: BackendFramework,
  technologies: Set<string>
): DatabaseSetup {
  const id: DatabaseSetupId = technologies.has("mongoose")
    ? "mongoose"
    : technologies.has("mongodb-driver") || technologies.has("mongodb")
      ? "mongodb-driver"
      : technologies.has("prisma")
        ? "prisma"
        : technologies.has("sequelize")
          ? "sequelize"
          : technologies.has("postgresql-driver") ||
              technologies.has("postgresql")
            ? "postgresql-driver"
            : "none";

  const noRoutes = {
    serverImport: "",
    serverConnect: "",
    routeImport: "",
    routeRegister: "",
  };

  if (id === "none") {
    return {
      id,
      env: commonEnv,
      files: [],
      scripts: {},
      ...noRoutes,
    };
  }

  const isMongo = id === "mongodb-driver" || id === "mongoose";
  const scripts: Record<string, string> =
    id === "prisma"
      ? {
          "db:generate": "prisma generate",
          "db:push": "prisma db push",
        }
      : {};

  return {
    id,
    env: [...commonEnv, ...(isMongo ? mongoEnv : postgresEnv)],
    files:
      id === "mongodb-driver"
        ? mongoDriverSetup(language, framework)
        : id === "mongoose"
          ? mongooseSetup(language, framework)
          : id === "postgresql-driver"
            ? postgresDriverSetup(language, framework)
            : id === "prisma"
              ? prismaSetup(language, framework)
              : sequelizeSetup(language, framework),
    scripts,
    serverImport:
      'const { connectToDatabase } = await import("./config/database.js");',
    serverConnect: "await connectToDatabase();",
    routeImport:
      framework === "express"
        ? 'import { todoRouter } from "./routes/todos.js";'
        : 'import { registerTodoRoutes } from "./routes/todos.js";',
    routeRegister:
      framework === "express"
        ? '  app.use("/api/todos", todoRouter);'
        : '  await app.register(registerTodoRoutes, { prefix: "/api/todos" });',
  };
}
